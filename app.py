# 2. 함수(def): 선택한 동물과 먹이를 입력받아 판별 결과 문장 리스트를 반환
def check_pet_food(animal, food):
    result_messages = []

    # 3. 반복문(for): food_data 리스트를 순회하며 일치하는 데이터 검색
    for item in food_data:
        saved_animal = item[0]
        saved_food = item[1]
        status = item[2]
        reason = item[3]

        if saved_animal == animal and saved_food == food:
            # 4. 조건문(if-elif-else): 상태에 따라 출력 문구 분기
            if status == "금지":
                result_messages.append(f"{animal}는 {food}를 먹으면 안됩니다.")
                result_messages.append(f"이유: {reason}")
            elif status == "소량":
                result_messages.append(f"{animal}는 {food}를 먹어도 됩니다.")
                result_messages.append(f"이유: {reason}")
                result_messages.append("먹어도되지만 소량만 줘야한다.")
            else:
                result_messages.append(f"{animal}는 {food}를 안심하고 먹어도 됩니다.")
                result_messages.append(f"이유: {reason}")
            return result_messages

    result_messages.append(f"{animal}의 {food} 정보가 아직 등록되지 않았습니다.")
    return result_messages


